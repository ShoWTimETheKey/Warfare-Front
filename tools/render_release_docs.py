#!/usr/bin/env python3
"""Render release/support documents from reviewed metadata; no network or game access.

Edit release/current.json, not generated player documents. Public historical notes
are preserved verbatim from release/history.json (apart from LF normalization).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
SHA256 = re.compile(r"[0-9a-f]{64}\Z")
GENERATED = "<!-- Generated by tools/render_release_docs.py; edit release/current.json. -->"


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def normalized(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def validate(current: dict, history: list) -> None:
    """Reject internally inconsistent facts rather than publishing guessed values."""
    assets = current["assets"]
    names = [asset["name"] for asset in assets]
    if len(names) != len(set(names)):
        raise ValueError("Release asset names must be unique")
    installer = [asset for asset in assets if asset["name"] == current["installer"]["name"]]
    if len(installer) != 1:
        raise ValueError("Exactly one matching installer asset is required")
    volumes = [asset for asset in assets if re.search(r"\.7z\.\d{3}$", asset["name"])]
    if len(assets) != len(volumes) + 1 or not volumes:
        raise ValueError("Metadata must describe the installer and every data volume")
    indexes = sorted(int(asset["name"].rsplit(".", 1)[1]) for asset in volumes)
    if indexes != list(range(1, len(volumes) + 1)):
        raise ValueError("Data volume indexes must be consecutive")
    if sum(asset["size"] for asset in volumes) != current["downloadBytes"]:
        raise ValueError("Data-volume sum does not match downloadBytes")
    if current["downloadBytes"] + current["installedBytes"] != current["oldSingleDriveComponentSumBytes"]:
        raise ValueError("Data and installed component sum is inconsistent")
    if current["recommendedFreeBytes"] <= current["oldSingleDriveComponentSumBytes"]:
        raise ValueError("Free-space recommendation must include headroom")
    prefix = f"https://github.com/{current['repository']}/releases/download/{current['tag']}/"
    for asset in assets:
        if not SHA256.fullmatch(asset["sha256"]) or asset["size"] <= 0:
            raise ValueError(f"Invalid hash or size: {asset['name']}")
        if asset["url"] != prefix + asset["name"]:
            raise ValueError(f"Unexpected asset URL: {asset['name']}")
    if current["installer"]["signed"] is not False:
        raise ValueError("Signature wording must be reviewed before changing signing status")
    if current["minimumPerformanceValidated"] is not False:
        raise ValueError("Hardware requirements need evidence and reviewed copy")
    tags = [item["tag"] for item in history]
    if len(tags) != len(set(tags)) or current["tag"] not in tags:
        raise ValueError("Historical public tags must be unique and include the current release")
    for item in history:
        dt.datetime.fromisoformat(item["published_at"].replace("Z", "+00:00"))
        if item.get("draft") or not item["notes"].strip():
            raise ValueError("Only published releases with their original notes belong in history")
    if next(item for item in history if item["tag"] == current["tag"])["notes"] != current["originalNotes"]:
        raise ValueError("Current originalNotes differ from the frozen public history")
    for locale in ("en", "zh-CN"):
        for key in ("intro", "repository", "install", "security", "storage", "compatibility",
                    "campaigns", "saves", "support", "scope", "terms", "attachments", "updates"):
            if not current["copy"][locale][key]:
                raise ValueError(f"Missing reviewed copy: {locale}/{key}")


def context(current: dict) -> dict:
    setup = next(a for a in current["assets"] if a["name"] == current["installer"]["name"])
    repo = f"https://github.com/{current['repository']}"
    gb = lambda value: f"{value / 1_000_000_000:.2f}".rstrip("0").rstrip(".")
    return {
        "version": current["version"], "tag": current["tag"],
        "repo_url": repo, "latest_url": repo + "/releases/latest",
        "issues_url": repo + "/issues/new/choose", "release_url": current["releaseUrl"],
        "setup_name": setup["name"], "setup_sha": setup["sha256"],
        "data_gb": gb(current["downloadBytes"]), "installed_gb": gb(current["installedBytes"]),
        "component_gb": gb(current["oldSingleDriveComponentSumBytes"]),
        "free_gb": gb(current["recommendedFreeBytes"]),
        "volume_count": len(current["assets"]) - 1,
        "scope_en": current["validation"]["scope"],
        "scope_zh": current["validation"]["scopeZh"],
        "focus_issue_en": current["validation"]["nativeWindowEarlierKnownIssue"],
    }


def section(current: dict, locale: str, key: str) -> str:
    spec = current["copy"][locale][key]
    ctx = context(current)
    return f"## {spec['title'].format(**ctx)}\n\n" + "\n\n".join(p.format(**ctx) for p in spec["paragraphs"])


def shared(current: dict, locale: str, keys: tuple[str, ...]) -> str:
    return "\n\n".join(section(current, locale, key) for key in keys)


def asset_table(current: dict) -> str:
    count = len(current["assets"]) - 1
    lines = ["## V" + current["version"] + " release files / 发行文件", "",
             f"All {count} data volumes belong to this release. 全部 {count} 卷须来自同一发行版。", "",
             "| File / 文件 | Bytes / 字节 | SHA-256 |", "| --- | ---: | --- |"]
    for asset in current["assets"]:
        lines.append(f"| [{asset['name']}]({asset['url']}) | {asset['size']} | `{asset['sha256']}` |")
    return "\n".join(lines)


def bilingual(current: dict, title: str, keys: tuple[str, ...], *, files: bool = False) -> str:
    output = f"# {title}\n\n"
    output += shared(current, "en", keys)
    output += "\n\n---\n\n# 简体中文\n\n" + shared(current, "zh-CN", keys)
    if files:
        output += "\n\n" + asset_table(current)
    return normalized(output)


def render(current: dict, history: list, root: Path = ROOT) -> dict[str, str]:
    validate(current, history)
    common = ("security", "storage", "scope")
    readme_keys = ("repository", "install", "security", "storage", "campaigns", "compatibility",
                   "updates", "saves", "support", "scope", "attachments", "terms")
    outputs = {}
    for locale, filename, language_link in (
        ("en", "README.md", "[简体中文](README.zh-CN.md)"),
        ("zh-CN", "README.zh-CN.md", "[English](README.md)"),
    ):
        copy = current["copy"][locale]
        text = f"{GENERATED}\n\n# Warfare Front\n\n{language_link}\n\n{copy['intro']}\n\n"
        if (root / "docs/media/battlefield.webp").is_file():
            text += f"![{copy['screenshotAlt']}](docs/media/battlefield.webp)\n\n"
            text += copy["screenshotCaption"] + "\n\n"
        text += shared(current, locale, readme_keys)
        outputs[filename] = normalized(text)
    base = f"docs/releases/{current['tag']}/"
    outputs[base + "RELEASE-BODY.md"] = bilingual(
        current, f"Warfare Front V{current['version']} — Windows installer",
        ("changes", "install", "campaigns", "compatibility", "updates") + common + ("attachments", "support",))
    notes = current["originalNotes"].rstrip() + "\n\n---\n\n"
    notes += bilingual(current, "Installation, security and review limits / 安装、安全与验收范围",
                       common + ("attachments", "support",))
    outputs[base + "ReleaseNotes.md"] = normalized(notes)
    outputs[base + "START-HERE.txt"] = bilingual(
        current, f"Warfare Front V{current['version']} — Start here / 安装须知",
        ("install", "updates", "campaigns", "compatibility") + common + ("attachments", "support",), files=True)
    outputs[base + "README-INSTALLED.txt"] = bilingual(
        current, f"Warfare Front V{current['version']} — Installed game / 已安装游戏",
        ("installed", "campaigns", "compatibility", "updates", "saves") + common + ("attachments", "support", "terms"))
    # The installer intentionally renames the release Markdown attachment to .txt.
    outputs[base + "install/ReleaseNotes.txt"] = outputs[base + "ReleaseNotes.md"]
    changelog = ["<!-- Generated by tools/render_release_docs.py; edit release/history.json. -->",
                 "", "# Changelog", "",
                 "Original published release notes, newest first. Tags and historical titles are preserved.",
                 "旧版仅供查阅；安装请前往 [最新发行版](https://github.com/" + current["repository"] + "/releases/latest)。", ""]
    for item in sorted(history, key=lambda x: x["published_at"], reverse=True):
        changelog.extend([f"## [{item['tag']}]({item['url']}) — {item['published_at'][:10]}", "",
                          item["title"], "", item["notes"].rstrip(), "", "---", ""])
    outputs["CHANGELOG.md"] = normalized("\n".join(changelog))
    return outputs


def check_outputs(root: Path, outputs: dict[str, str]) -> list[str]:
    """Compare exact UTF-8 bytes; --check never repairs drift silently."""
    return [name for name, content in outputs.items()
            if not (root / name).is_file() or (root / name).read_bytes() != content.encode("utf-8")]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without writing")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve()
        current = read_json(root / "release/current.json")
        history = read_json(root / "release/history.json")
        outputs = render(current, history, root)
        if args.check:
            drift = check_outputs(root, outputs)
            if drift:
                print("Generated document drift: " + ", ".join(drift), file=sys.stderr)
                return 1
            print(f"Checked {len(outputs)} generated documents; no drift.")
            return 0
        for name, content in outputs.items():
            destination = root / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content.encode("utf-8"))
        print(f"Rendered {len(outputs)} documents from release metadata.")
        return 0
    except (KeyError, ValueError, OSError) as exc:
        print(f"Release documentation error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
